-- Emits docs/generated/DB_CATALOG.md from the PostgreSQL system catalogs (run by scripts/db-schema.sh).
-- Output must be deterministic: every list is ordered by name.
\pset format unaligned
\pset tuples_only on
\pset footer off

SELECT '# Database catalog (generated)

Generated by `npm run db:schema` from a database built only from `supabase/migrations/`. Do not edit by hand:
change a migration, regenerate, and commit both. Design rationale: [../DATABASE.md](../DATABASE.md).
Full DDL: [supabase/schema.sql](../../supabase/schema.sql).

## Tables

| Table | Columns | RLS | Policies | Client grants | Purpose |
|---|---:|---|---:|---|---|';
SELECT format('| `%s` | %s | %s | %s | %s | %s |', c.relname,
  (SELECT count(*) FROM pg_attribute a WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped),
  CASE WHEN c.relrowsecurity THEN 'on' ELSE '**off**' END,
  (SELECT count(*) FROM pg_policy p WHERE p.polrelid = c.oid),
  CASE WHEN has_any_column_privilege('anon', c.oid, 'SELECT') OR has_any_column_privilege('authenticated', c.oid, 'SELECT')
    THEN '**yes**' ELSE 'none' END,
  coalesce(replace(obj_description(c.oid, 'pg_class'), '|', '/'), ''))
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r'
ORDER BY c.relname;

SELECT '
## Views

| View | security_invoker | Client grants |
|---|---|---|';
SELECT format('| `%s` | %s | %s |', c.relname,
  coalesce('security_invoker=true' = ANY (c.reloptions), false),
  CASE WHEN has_any_column_privilege('anon', c.oid, 'SELECT') OR has_any_column_privilege('authenticated', c.oid, 'SELECT')
    THEN '**yes**' ELSE 'none' END)
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'v'
ORDER BY c.relname;

SELECT '
## Functions (RPC)

All are `SECURITY INVOKER` with `search_path = ''` unless marked. `service_role` = executable by the backend.

| Function | Returns | Volatility | service_role | Note |
|---|---|---|---|---|';
SELECT format('| `%s(%s)` | %s | %s | %s | %s |', p.proname, pg_get_function_identity_arguments(p.oid),
  pg_get_function_result(p.oid),
  CASE p.provolatile WHEN 'i' THEN 'immutable' WHEN 's' THEN 'stable' ELSE 'volatile' END,
  CASE WHEN has_function_privilege('service_role', p.oid, 'EXECUTE') THEN 'yes' ELSE 'no' END,
  concat_ws('; ',
    CASE WHEN p.prosecdef THEN '**SECURITY DEFINER**' END,
    CASE WHEN NOT coalesce('search_path=""' = ANY (p.proconfig), false) THEN '**mutable search_path**' END,
    replace(obj_description(p.oid, 'pg_proc'), '|', '/')))
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'public'
ORDER BY p.proname, pg_get_function_identity_arguments(p.oid);

SELECT '
## Triggers

| Trigger | Table | Function |
|---|---|---|';
SELECT format('| `%s` | `%s` | `%s` |', t.tgname, c.relname, p.proname)
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace JOIN pg_proc p ON p.oid = t.tgfoid
WHERE n.nspname = 'public' AND NOT t.tgisinternal
ORDER BY t.tgname;

SELECT '
## Indexes

| Index | Table | Definition |
|---|---|---|';
SELECT format('| `%s` | `%s` | `%s` |', i.relname, t.relname,
  regexp_replace(pg_get_indexdef(x.indexrelid), '^CREATE (UNIQUE )?INDEX \S+ ON \S+ USING ', '\1'))
FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class t ON t.oid = x.indrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
WHERE n.nspname = 'public'
ORDER BY t.relname, i.relname;

SELECT '
## Foreign keys

| Table | Constraint | References | On delete |
|---|---|---|---|';
SELECT format('| `%s` | `%s` | `%s` | %s |', c.conrelid::regclass, c.conname,
  regexp_replace(pg_get_constraintdef(c.oid), '^FOREIGN KEY ', ''),
  CASE c.confdeltype WHEN 'c' THEN 'cascade' WHEN 'n' THEN 'set null' WHEN 'r' THEN 'restrict' ELSE 'no action' END)
FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace
WHERE n.nspname = 'public' AND c.contype = 'f'
ORDER BY c.conrelid::regclass::text, c.conname;

SELECT '
## Totals
';
SELECT format('- Tables: %s, views: %s, functions: %s, triggers: %s, indexes: %s, policies: %s, foreign keys: %s, check constraints: %s',
  (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind = 'r'),
  (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind = 'v'),
  (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public'),
  (SELECT count(*) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal),
  (SELECT count(*) FROM pg_index x JOIN pg_class t ON t.oid = x.indrelid JOIN pg_namespace n ON n.oid = t.relnamespace WHERE n.nspname = 'public'),
  (SELECT count(*) FROM pg_policies WHERE schemaname = 'public'),
  (SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace WHERE n.nspname = 'public' AND c.contype = 'f'),
  (SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace WHERE n.nspname = 'public' AND c.contype = 'c'));
